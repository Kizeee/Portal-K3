CREATE TABLE IF NOT EXISTS public.admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.reports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_hash text NOT NULL UNIQUE,
  reporter text NOT NULL DEFAULT '',
  category text NOT NULL,
  incident_date date NOT NULL,
  location text NOT NULL,
  description text NOT NULL,
  initial_action text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'Baru'
    CHECK (status IN ('Baru', 'Ditinjau', 'Ditindaklanjuti', 'Selesai')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.status_updates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id integer NOT NULL REFERENCES public.reports(id) ON DELETE CASCADE,
  status text NOT NULL
    CHECK (status IN ('Baru', 'Ditinjau', 'Ditindaklanjuti', 'Selesai')),
  note text NOT NULL DEFAULT '',
  changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS reports_created_at_idx ON public.reports(created_at DESC);
CREATE INDEX IF NOT EXISTS status_updates_report_id_idx ON public.status_updates(report_id, id);

ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.status_updates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.admins, public.reports, public.status_updates FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.admins_id_seq, public.reports_id_seq, public.status_updates_id_seq FROM anon, authenticated;
